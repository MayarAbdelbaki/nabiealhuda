import logging
import time

import requests

from odoo import _, api, fields, models
from odoo.exceptions import UserError, ValidationError

from odoo.addons.msegat_integration import const

_logger = logging.getLogger(__name__)

# T2 Communicate JWTs, valid one hour: {(db, company id, api url, email): (token, expiry timestamp)}
_whatsapp_tokens = {}


class MsegatError(UserError):
    """ Msegat answered, but refused the request. """

    def __init__(self, message, code):
        super().__init__(message)
        self.code = code


class ResCompany(models.Model):
    _inherit = 'res.company'

    msegat_username = fields.Char(string="Msegat Username")
    msegat_api_key = fields.Char(string="Msegat API Key", groups='base.group_system')
    msegat_sender = fields.Char(
        string="Msegat Sender Name",
        help="Sender name activated in your Msegat account (11 characters max). "
             "Use 'auth-mseg' to test verification codes for free.",
    )
    msegat_otp_login = fields.Boolean(
        string="Verify the Phone of New External Users",
        help="External users created from now on (website sign-up, portal invitation) confirm their phone number "
             "with a code sent by SMS at their first login. Later logins only need the password.",
    )
    msegat_otp_method = fields.Selection(
        selection=[
            ('api', "Msegat OTP service"),
            ('sms', "Code generated by Odoo, sent as an SMS"),
        ],
        string="Verification Code Method",
        default='api',
        required=True,
    )
    msegat_otp_lang = fields.Selection(
        selection=[('Ar', "Arabic"), ('En', "English")],
        string="Verification Code Language",
        default='Ar',
        required=True,
    )
    msegat_otp_message = fields.Char(
        string="Verification Code Message",
        default="Pin Code is: {code}",
        help="SMS text when Odoo generates the code; {code} is replaced by the code.",
    )
    msegat_whatsapp_url = fields.Char(string="WhatsApp API URL", default=const.WHATSAPP_API_URL)
    msegat_whatsapp_email = fields.Char(string="WhatsApp Account Email")
    msegat_whatsapp_password = fields.Char(string="WhatsApp Account Password", groups='base.group_system')
    msegat_whatsapp_mode = fields.Selection(
        selection=[
            ('template', "Approved template with a document header"),
            ('document', "PDF message (only within 24h of the customer's last message)"),
        ],
        string="WhatsApp Invoice Message",
        default='template',
        required=True,
    )
    msegat_whatsapp_template = fields.Char(
        string="Msegat WhatsApp Template",
        help="Template approved by Meta in your Msegat WhatsApp account, with a document header.",
    )
    msegat_whatsapp_template_params = fields.Char(
        string="Template Variables",
        default='partner_name,invoice_number,amount_total',
        help="Comma-separated values for the template body variables, in order. Available: %s."
             % ', '.join(const.WHATSAPP_TEMPLATE_VARIABLES),
    )

    @api.constrains('msegat_otp_method', 'msegat_otp_message')
    def _check_msegat_otp_message(self):
        for company in self:
            if company.msegat_otp_method == 'sms' and '{code}' not in (company.msegat_otp_message or ''):
                raise ValidationError(_("The verification code message must contain {code}."))

    @api.constrains('msegat_whatsapp_template_params')
    def _check_msegat_whatsapp_template_params(self):
        for company in self:
            unknown = set(company._msegat_whatsapp_template_keys()) - set(const.WHATSAPP_TEMPLATE_VARIABLES)
            if unknown:
                raise ValidationError(_(
                    "Unknown WhatsApp template variables: %(unknown)s. Available: %(available)s.",
                    unknown=', '.join(sorted(unknown)),
                    available=', '.join(const.WHATSAPP_TEMPLATE_VARIABLES),
                ))

    def _msegat_whatsapp_template_keys(self):
        self.ensure_one()
        return [key.strip() for key in (self.msegat_whatsapp_template_params or '').split(',') if key.strip()]

    # === MSEGAT SMS GATEWAY === #

    def _msegat_credentials(self):
        self.ensure_one()
        company = self.sudo()
        if not (company.msegat_username and company.msegat_api_key and company.msegat_sender):
            raise UserError(_(
                "Msegat is not configured for %s: set the username, API key and sender name in the Settings.",
                self.name,
            ))
        return {'userName': company.msegat_username, 'apiKey': company.msegat_api_key}

    def _msegat_request(self, endpoint, payload, headers=None):
        """ POST `payload` as JSON to an Msegat gateway endpoint.

        :return: the decoded answer
        :raise MsegatError: when Msegat refuses the request
        :raise UserError: when Msegat cannot be reached
        """
        data = {**self._msegat_credentials(), **payload}
        try:
            response = requests.post(
                const.MSEGAT_API_URL + endpoint, json=data, headers=headers, timeout=const.REQUEST_TIMEOUT,
            )
            response.raise_for_status()
            result = response.json()
        except (requests.RequestException, ValueError) as e:
            _logger.warning("Msegat %s request failed: %s", endpoint, e)
            raise UserError(_("Could not reach Msegat: %s", e)) from e
        if not isinstance(result, dict):
            result = {'code': str(result)}
        code = str(result.get('code'))
        if code not in const.MSEGAT_SUCCESS_CODES:
            self._msegat_raise(endpoint, code, result.get('message'))
        return result

    def _msegat_raise(self, endpoint, code, message=None):
        message = message or const.MSEGAT_ERROR_MESSAGES.get(code) or code
        _logger.warning("Msegat %s refused the request: %s (%s)", endpoint, message, code)
        raise MsegatError(_("Msegat error %(code)s: %(message)s", code=code, message=message), code)

    def _msegat_get_balance(self):
        """ Return the remaining points of the Msegat account. """
        try:
            response = requests.get(
                const.MSEGAT_API_URL + 'Credits.php', params=self._msegat_credentials(), timeout=const.REQUEST_TIMEOUT,
            )
            response.raise_for_status()
        except requests.RequestException as e:
            raise UserError(_("Could not reach Msegat: %s", e)) from e
        answer = response.text.strip()
        try:
            return float(answer)
        except ValueError:
            pass
        # Errors come back either as a bare code or as JSON.
        try:
            result = response.json()
        except ValueError:
            result = {'code': answer}
        self._msegat_raise('Credits.php', str(result.get('code')), result.get('message'))

    def _msegat_send_sms(self, number, message):
        """ Send `message` to `number` (international format without + or 00, e.g. 9665XXXXXXXX). """
        return self._msegat_request('sendsms.php', {
            'numbers': number,
            'userSender': self.sudo().msegat_sender,
            'msg': message,
            'msgEncoding': 'UTF8',
        })

    def _msegat_send_otp(self, number):
        """ Have Msegat generate a code and send it to `number`.

        :return: the Msegat id needed to verify the code
        """
        lang = self.msegat_otp_lang
        result = self._msegat_request(
            'sendOTPCode.php',
            {'number': number, 'userSender': self.sudo().msegat_sender, 'lang': lang},
            headers={'lang': lang},
        )
        if not result.get('id'):
            raise UserError(_("Msegat did not return an id for the verification code."))
        return str(result['id'])

    def _msegat_verify_otp(self, code_id, code):
        """ Return whether Msegat accepts `code` for the verification `code_id`. """
        lang = self.msegat_otp_lang
        try:
            self._msegat_request(
                'verifyOTPCode.php',
                {
                    'id': int(code_id) if code_id.isdigit() else code_id,
                    'code': code,
                    'userSender': self.sudo().msegat_sender,
                    'lang': lang,
                },
                headers={'lang': lang},
            )
        except MsegatError:
            return False
        return True

    # === MSEGAT WHATSAPP (T2 COMMUNICATE) === #

    def _msegat_whatsapp_post(self, path, payload, token=None):
        url = (self.sudo().msegat_whatsapp_url or const.WHATSAPP_API_URL).rstrip('/') + path
        headers = {'Authorization': f'Bearer {token}'} if token else None
        try:
            return requests.post(url, json=payload, headers=headers, timeout=const.REQUEST_TIMEOUT)
        except requests.RequestException as e:
            _logger.warning("WhatsApp API %s request failed: %s", path, e)
            raise UserError(_("Could not reach the WhatsApp API: %s", e)) from e

    def _msegat_whatsapp_result(self, path, response):
        try:
            result = response.json()
        except ValueError:
            result = None
        if not isinstance(result, dict):
            result = {}
        if not response.ok or result.get('success') is False:
            message = result.get('message') or result.get('Message') or response.text[:200] or response.reason
            _logger.warning("WhatsApp API %s refused the request (%s): %s", path, response.status_code, message)
            raise UserError(_(
                "WhatsApp API error (%(status)s): %(message)s", status=response.status_code, message=message,
            ))
        return result

    def _msegat_whatsapp_token(self, refresh=False):
        """ Return a T2 Communicate JWT, logging in when there is no valid one yet. """
        self.ensure_one()
        company = self.sudo()
        if not (company.msegat_whatsapp_email and company.msegat_whatsapp_password):
            raise UserError(_(
                "Msegat WhatsApp is not configured for %s: set the account email and password in the Settings.",
                self.name,
            ))
        key = (self.env.cr.dbname, self.id, company.msegat_whatsapp_url, company.msegat_whatsapp_email)
        token, expires_at = _whatsapp_tokens.get(key, (None, 0))
        if refresh or not token or expires_at <= time.time():
            credentials = {'email': company.msegat_whatsapp_email, 'password': company.msegat_whatsapp_password}
            result = self._msegat_whatsapp_result('/auth/login', self._msegat_whatsapp_post('/auth/login', credentials))
            token = result.get('token')
            if not token:
                raise UserError(_("The WhatsApp API login did not return a token."))
            # Renew a few minutes before the actual expiry.
            _whatsapp_tokens[key] = (token, time.time() + int(result.get('expireInSeconds') or 3600) - 300)
        return token

    def _msegat_whatsapp_send(self, payload):
        """ Send a message through `/message/send-custom`, logging in again once if the token was revoked. """
        path = '/message/send-custom'
        response = self._msegat_whatsapp_post(path, payload, self._msegat_whatsapp_token())
        if response.status_code == 401:
            response = self._msegat_whatsapp_post(path, payload, self._msegat_whatsapp_token(refresh=True))
        return self._msegat_whatsapp_result(path, response)
